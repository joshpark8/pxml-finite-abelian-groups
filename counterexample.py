"""Gassmann-type pairs for a finite abelian group, via marks on the subgroup lattice.

A G-set is a disjoint union of coset spaces G/S.  For abelian G the mark |X^T|
depends only on *which* summands contain T, so the whole Burnside-ring
computation reduces to a question about the subgroup lattice.

We look for X, Y with the same permutation character (equal marks at every
cyclic subgroup, i.e. |X^g| = |Y^g| for all g) but different marks somewhere.
Since the mark homomorphism is injective, any such pair is non-isomorphic.

Two notions of "pair" are reported.  The weak one asks only for equal
permutation characters; the strong one also demands equal multisets of orbit
sizes.  They differ: in Z_2 x Z_2 a weak pair exists but no strong one, so a
weak pair there is no counterexample to a statement that assumes equal orbits.

Run:  python counterexample.py [invariant factors] [--weak] [--max N]
      python counterexample.py 2 4 8     ->  Z_2 x Z_4 x Z_8   (default)
      python counterexample.py 2 2 2     ->  the Z_2^3 example
      python counterexample.py 2 2 --weak
"""

import sys
from collections import defaultdict
from fractions import Fraction
from itertools import combinations_with_replacement, product

INVARIANTS = (2,4,8)

NG = 0          # |G|, set by setup()
INV = ()        # invariant factors, set by setup()


# ---------------------------------------------------------------- group setup

def setup(inv):
    global NG, INV
    INV, NG = tuple(inv), 1
    for m in INV:
        NG *= m
    return [tuple(e) for e in product(*(range(m) for m in INV))]


def add(a, b):
    return tuple((x + y) % m for x, y, m in zip(a, b, INV))


def smul(c, a):
    return tuple((c * x) % m for x, m in zip(a, INV))


def identity():
    return tuple(0 for _ in INV)


def span(gens):
    """Subgroup generated by gens (replaces the XOR-closure of the Z_2^n case)."""
    S, frontier = {identity()}, [identity()]
    while frontier:
        s = frontier.pop()
        for g in gens:
            t = add(s, g)
            if t not in S:
                S.add(t)
                frontier.append(t)
    return frozenset(S)


def all_subgroups(G):
    """Every subgroup, by closing each known subgroup under one more element."""
    subs = {frozenset({identity()})}
    frontier = list(subs)
    while frontier:
        new = []
        for S in frontier:
            for g in G:
                if g in S:
                    continue
                T = span(list(S) + [g])
                if T not in subs:
                    subs.add(T)
                    new.append(T)
        frontier = new
    return sorted(subs, key=lambda S: (len(S), sorted(S)))


def cyclic_subgroups(G):
    return sorted({span([g]) for g in G}, key=lambda S: (len(S), sorted(S)))


# ------------------------------------------------------------------- marks

def M(Xs, T):
    # T-orbits on G/S all have size |T|/|T∩S|
    return sum(NG * len(T & S) // (len(T) * len(S)) for S in Xs)


def mark(Xs, T):
    # T fixes G/S pointwise iff T <= S
    return sum(NG // len(S) for S in Xs if T <= S)


def character(Xs, cyclics):
    """Permutation character: chi_X(g) = |X^<g>|, tabulated over cyclic subgroups."""
    return tuple(mark(Xs, C) for C in cyclics)


def marks(Xs, subs):
    return tuple(mark(Xs, T) for T in subs)


# -------------------------------------------------------------------- naming

def iso_type(S):
    """Name S by isomorphism type in invariant-factor form, e.g. 'Z8xZ4xZ2'.

    For each prime p, |{x in S : p^k x = 0}| = p^(sum_i min(lambda_i, k)) pins the
    partition lambda of the p-primary part; the invariant factors are then read off
    by multiplying the i-th largest p-part across all p."""
    n = len(S)
    if n == 1:
        return "1"
    primes, m = [], n
    d = 2
    while d * d <= m:
        if m % d == 0:
            primes.append(d)
            while m % d == 0:
                m //= d
        d += 1
    if m > 1:
        primes.append(m)

    primary = {}
    for p in primes:
        ranks, k = [0], 1
        while True:
            killed = sum(1 for x in S if smul(p ** k, x) == identity())
            r = 0
            while p ** r < killed:
                r += 1
            if r == ranks[-1]:          # p-primary part exhausted; stop
                break
            ranks.append(r)
            k += 1
        # gaps[k] = #{parts >= k+1}, so #{parts == k+1} = gaps[k] - gaps[k+1]
        gaps = [ranks[i] - ranks[i - 1] for i in range(1, len(ranks))] + [0]
        parts = []
        for i in range(len(gaps) - 1):
            parts += [p ** (i + 1)] * (gaps[i] - gaps[i + 1])
        primary[p] = sorted(parts, reverse=True)

    width = max(len(v) for v in primary.values())
    factors = []
    for i in range(width):
        f = 1
        for p, parts in primary.items():
            if i < len(parts):
                f *= parts[i]
        factors.append(f)
    return "x".join("Z%d" % f for f in factors)


def make_names(subs, G):
    """Short, stable label per subgroup: isomorphism type, disambiguated by index."""
    by_type = defaultdict(list)
    for S in subs:
        by_type[iso_type(S)].append(S)
    names = {}
    for t, group in by_type.items():
        for i, S in enumerate(group, 1):
            names[S] = t if len(group) == 1 else "%s#%d" % (t, i)
    names[frozenset({identity()})] = "1"
    names[frozenset(G)] = "G"
    return names


# ------------------------------------------------------- exact existence test

def orbit_sizes(Xs):
    """Multiset of G-orbit sizes of the G-set X = disjoint union of G/S."""
    return tuple(sorted(NG // len(S) for S in Xs))


def _rank(rows, n):
    """Rank over Q of a list of rows of length n, by exact Gaussian elimination."""
    A = [r[:] for r in rows]
    r = 0
    for col in range(n):
        p = next((i for i in range(r, len(A)) if A[i][col] != 0), None)
        if p is None:
            continue
        A[r], A[p] = A[p], A[r]
        f = A[r][col]
        A[r] = [x / f for x in A[r]]
        for i in range(len(A)):
            if i != r and A[i][col] != 0:
                g = A[i][col]
                A[i] = [x - g * y for x, y in zip(A[i], A[r])]
        r += 1
        if r == len(A):
            break
    return r


def kernel_dims(subs, cyclics):
    """Exact existence test, with no bound on the number of summands.

    Write a G-set as an integer vector over the subgroups (multiplicity of G/S).
    Rows of A force equal permutation character; the extra rows force equal
    multisets of orbit sizes.  A pair X != Y exists iff the kernel is nonzero:
    any integer v in the kernel splits as v+ - v-, and the two G-sets it names
    are non-isomorphic because the full mark homomorphism is injective.

    Returns (weak, strong) kernel dimensions."""
    n = len(subs)
    char_rows = [[Fraction(NG // len(S)) if C <= S else Fraction(0) for S in subs]
                 for C in cyclics]
    size_rows = [[Fraction(1) if NG // len(S) == d else Fraction(0) for S in subs]
                 for d in sorted({NG // len(S) for S in subs})]
    return n - _rank(char_rows, n), n - _rank(char_rows + size_rows, n)


# -------------------------------------------------------------------- search

def find_pair(subs, cyclics, max_summands=3, match_orbit_sizes=True):
    """Smallest explicit X, Y sharing a permutation character but no summand.

    Ranked by number of points, then by total summands.  Multisets of *every*
    size up to max_summands go into one bucket table, so an X with two summands
    is still compared against a Y with three.  G is a legal summand: excluding
    it loses real pairs (in Z_2 x Z_2 every pair needs G/G, since G is the only
    non-cyclic subgroup and so the only place marks can differ).

    With match_orbit_sizes, X and Y must also have the same multiset of orbit
    sizes -- the stronger notion, and then necessarily the same summand count."""
    buckets = defaultdict(list)
    for size in range(1, max_summands + 1):
        for combo in combinations_with_replacement(subs, size):
            key = character(combo, cyclics)
            if match_orbit_sizes:
                key = (key, orbit_sizes(combo))
            buckets[key].append(combo)

    best = None
    for lst in buckets.values():
        for i in range(len(lst)):
            for j in range(i + 1, len(lst)):
                A, B = lst[i], lst[j]
                if set(A) & set(B):          # cancel shared summands: WLOG disjoint
                    continue
                cand = (mark(A, frozenset({identity()})), len(A) + len(B), A, B)
                if best is None or cand[:2] < best[:2]:
                    best = cand
    return (best[2], best[3]) if best else (None, None)


# ---------------------------------------------------------------------- main

def main(inv, max_summands=3, match_orbit_sizes=True):
    G = setup(inv)
    subs = all_subgroups(G)
    cyclics = cyclic_subgroups(G)
    names = make_names(subs, G)

    print("G = " + " x ".join("Z%d" % m for m in INV) + "   |G| = %d" % NG)
    print("subgroups: %d   cyclic subgroups: %d" % (len(subs), len(cyclics)))

    weak, strong = kernel_dims(subs, cyclics)
    print("\nexistence (exact, no bound on summands):")
    print("  equal permutation character           : kernel dim %-3d -> %s"
          % (weak, "pairs exist" if weak else "NONE"))
    print("  ... and equal multiset of orbit sizes : kernel dim %-3d -> %s"
          % (strong, "pairs exist" if strong else "NONE"))

    want = strong if match_orbit_sizes else weak
    print("\nsearching for an explicit pair (<= %d summands, orbit sizes %s)"
          % (max_summands, "matched" if match_orbit_sizes else "unconstrained"))
    X, Y = find_pair(subs, cyclics, max_summands, match_orbit_sizes)
    if X is None:
        if want:
            print("  none at this bound -- but one EXISTS; raise --max")
        else:
            print("  none, and none exist")
        return

    print("\nX = " + " + ".join("G/" + names[S] for S in X) + "    orbit sizes " + str(list(orbit_sizes(X))))
    print("Y = " + " + ".join("G/" + names[S] for S in Y) + "    orbit sizes " + str(list(orbit_sizes(Y))))
    print("|X| = |Y| = %d\n" % mark(X, frozenset({identity()})))

    mX, mY = marks(X, subs), marks(Y, subs)
    cyc = set(cyclics)
    print("%14s %4s %5s %5s %6s %6s" % ("T", "|T|", "M(X)", "M(Y)", "|X^T|", "|Y^T|"))
    ndiff = 0
    for T, a, b in zip(subs, mX, mY):
        tags = []
        if M(X, T) != M(Y, T):
            tags.append("M differs")
        if a != b:
            tags.append("<<<")
            ndiff += 1
        if T in cyc:
            tags.append("cyclic")
        print("%14s %4d %5d %5d %6d %6d  %s"
              % (names[T], len(T), M(X, T), M(Y, T), a, b, ", ".join(tags)))

    print("\nsame permutation character (|X^g| = |Y^g| for all g): %s"
          % all(mark(X, C) == mark(Y, C) for C in cyclics))
    print("same multiset of orbit sizes: %s" % (orbit_sizes(X) == orbit_sizes(Y)))
    print("marks differ at %d of %d subgroups -> X and Y are not isomorphic"
          % (ndiff, len(subs)))


if __name__ == "__main__":
    args = sys.argv[1:]
    weak_only = "--weak" in args
    args = [a for a in args if a != "--weak"]
    bound = 3
    if "--max" in args:
        i = args.index("--max")
        bound = int(args[i + 1])
        args = args[:i] + args[i + 2:]
    main([int(a) for a in args] or INVARIANTS, bound, not weak_only)
